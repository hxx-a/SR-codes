%% 二维标准三稳
function x=lgkt1(c,d,v,k,r,h,x1)
x=zeros(1,length(x1));
y=zeros(1,length(x1));
for i=1:length(x1)-1
    if abs(x(i))>2
        x(i)=sign(x(i))*2;
    end
    if abs(y(i))>2
        y(i)=sign(x(i))*2;
    end

        k1=6.*v.*x(i).^2/(c.^2+d.^2)-3.*v.*x(i).^4/(c.^2.*d.^2)+2.*v.*x(i).^6/((c.^2.*d.^2).*(c.^2+d.^2))+r*(y(i)-x(i))+x1(i);
        f1=-k*y(i)+r*(x(i)-y(i));
        k2=6.*v.*(x(i)+k1*h/2).^2/(c.^2+d.^2)-3.*v.*(x(i)+k1*h/2).^4/(c.^2.*d.^2)+2.*v.*(x(i)+k1*h/2).^6/((c.^2.*d.^2).*(c.^2+d.^2))+r*(y(i)-(x(i)+k1*h/2))+(x1(i)+h/2);
        f2=-k*(y(i)+f1*h/2)+r*(x(i)-(y(i)+f1*h/2));
        k3=6.*v.*(x(i)+k2*h/2).^2/(c.^2+d.^2)-3.*v.*(x(i)+k2*h/2).^4/(c.^2.*d.^2)+2.*v.*(x(i)+k2*h/2).^6/((c.^2.*d.^2).*(c.^2+d.^2))+r*(y(i)-(x(i)+k2*h/2))+(x1(i)+h/2);
        f3=-k*(y(i)+f2*h/2)+r*(x(i)-(y(i)+f2*h/2));
        k4=6.*v.*(x1(i)+h).^2/(c.^2+d.^2)-3.*v.*(x1(i)+h).^4/(c.^2.*d.^2)+2.*v.*(x1(i)+h).^6/((c.^2.*d.^2).*(c.^2+d.^2))+r*(y(i)-(x(i)+k3*h))+(x1(i)+h);
        f4=-k*(y(i)+f3*h)+r*(x(i)-(y(i)+f3*h));
        x(i+1)=x(i)+1/6*h*(k1+2*k2+2*k3+k4);
        y(i+1)=y(i)+1/6*h*(f1+2*f2+2*f3+f4);    
    
end