%% 这是一维的标准三稳
function x=lgkt0(c,d,v,h,x1)
x=zeros(1,length(x1));


for i=1:length(x1)-1

    k1=(-12*v*x(i)/(c.^2+d.^2)+12*v*x(i).^3/(c.^2*d.^2)-12*v*x(i).^5/(c.^2*d.^2*(c.^2+d.^2))+x1(i));
    k2=(-12*v*(x(i)+k1*h/2)/(c.^2+d.^2)+12*v*(x(i)+k1*h/2).^3/(c.^2*d.^2)-12*v*(x(i)+k1*h/2).^5/(c.^2*d.^2*(c.^2+d.^2))+x1(i)+h/2);
    k3=(-12*v*(x(i)+k2*h/2)/(c.^2+d.^2)+12*v*(x(i)+k2*h/2).^3/(c.^2*d.^2)-12*v*(x(i)+k2*h/2).^5/(c.^2*d.^2*(c.^2+d.^2))+x1(i)+h/2);
    k4=(-12*v*(x(i)+k3*h)/(c.^2+d.^2)+12*v*(x(i)+k3*h).^3/(c.^2*d.^2)-12*v*(x(i)+k3*h).^5/(c.^2*d.^2*(c.^2+d.^2))+x1(i)+h);
    x(i+1)=x(i)+(1/6)*h*(k1+2*k2+2*k3+k4);
end
end